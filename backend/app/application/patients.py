"""Records of the patient plane: patient, recorded facts, evaluations, projections.

Everything a site records is an append-only fact keyed by the LOGICAL visit
(patient + schedule version + event code + occurrence index), never by the id of
a projected row. A projection row is regenerated by every evaluation; the fact
about what really happened survives it by construction (P1-03).
"""

from __future__ import annotations

from datetime import date, datetime
from typing import Any
from uuid import UUID, uuid4

from pydantic import Field

from .records import Record, utc_now


class PatientRecord(Record):
    id: UUID = Field(default_factory=uuid4)
    organization_id: UUID
    trial_id: UUID
    site_id: UUID | None = None
    patient_code: str
    current_schedule_version_id: UUID | None = None
    arm_id: UUID | None = None
    cohort_id: UUID | None = None
    population_id: UUID | None = None
    #: Codes are stored beside the ids so a version change never loses them.
    arm_code: str | None = None
    cohort_code: str | None = None
    population_code: str | None = None
    dimension_values: dict[str, Any] = Field(default_factory=dict)
    status: str = "ACTIVE"
    external_patient_id: str | None = None
    created_at: datetime = Field(default_factory=utc_now)
    updated_at: datetime = Field(default_factory=utc_now)
    revision: int = 0


class PatientAnchorRecord(Record):
    id: UUID = Field(default_factory=uuid4)
    organization_id: UUID
    patient_id: UUID
    anchor_definition_id: UUID
    anchor_code: str
    value_date: date | None = None
    value_datetime: datetime | None = None
    status: str
    source_type: str | None = None
    source_reference: dict[str, Any] | None = None
    recorded_by: UUID | None = None
    recorded_at: datetime = Field(default_factory=utc_now)
    metadata: dict[str, Any] = Field(default_factory=dict)


class PatientStateRecord(Record):
    id: UUID = Field(default_factory=uuid4)
